def crc8(data: bytes, init: int = CRC8_INIT) -> int:
    c = init
    for b in data:
        c = CRC8_TABLE[(c ^ b) & 0xFF]
    return c & 0xFF


def crc16(data: bytes, init: int = CRC16_INIT) -> int:
    c = init
    for b in data:
        c = (CRC16_TABLE[(c ^ b) & 0xFF] ^ (c >> 8)) & 0xFFFF
    return c & 0xFFFF


@dataclass
class Packet:
    cmd_set: int
    cmd_id: int
    payload: bytes = b""
    src: int = ADDR_PC_APP
    dst: int = ADDR_FLYC
    seq: int = 0
    cmd_type: int = 0x40  # request; confirm exact flag byte from a live capture
    version: int = 1

    def build(self) -> bytes:
        length = 13 + len(self.payload)  # 11 header + 2 crc16 + payload
        if length > 0x3FF:
            raise ValueError("DUML packet too long (10-bit length field)")
        hdr = bytes([
            0x55,
            length & 0xFF,
            ((self.version & 0x3F) << 2) | ((length >> 8) & 0x03),
        ])
        hdr += bytes([crc8(hdr)])
        body = hdr + bytes([
            self.src & 0xFF, self.dst & 0xFF,
            self.seq & 0xFF, (self.seq >> 8) & 0xFF,
            self.cmd_type & 0xFF, self.cmd_set & 0xFF, self.cmd_id & 0xFF,
        ]) + self.payload
        c = crc16(body)
        return body + bytes([c & 0xFF, (c >> 8) & 0xFF])

    @classmethod
    def parse(cls, raw: bytes) -> "Packet":
        if len(raw) < 13 or raw[0] != 0x55:
            raise ValueError("not a DUML packet")
        length = raw[1] | ((raw[2] & 0x03) << 8)
        if len(raw) < length:
            raise ValueError(f"truncated: have {len(raw)}, need {length}")
        if crc8(raw[0:3]) != raw[3]:
            raise ValueError("header CRC8 mismatch")
        if crc16(raw[0:length - 2]) != (raw[length - 2] | (raw[length - 1] << 8)):
            raise ValueError("footer CRC16 mismatch")
        return cls(
            src=raw[4], dst=raw[5], seq=raw[6] | (raw[7] << 8),
            cmd_type=raw[8], cmd_set=raw[9], cmd_id=raw[10],
            payload=bytes(raw[11:length - 2]),
        )


def iter_packets(buf: bytes):
    """Yield (packet_bytes, consumed) for every valid DUML frame in a byte stream.
    Resynchronises on 0x55 + valid header CRC8, so it tolerates the bulk-endpoint
    read boundaries not lining up with packet boundaries."""
    i = 0
    n = len(buf)
    while i < n:
        if buf[i] != 0x55:
            i += 1
            continue
        if i + 4 > n:
            break
        length = buf[i + 1] | ((buf[i + 2] & 0x03) << 8)
        if length < 13 or i + length > n:
            i += 1
            continue
        if crc8(buf[i:i + 3]) != buf[i + 3]:
            i += 1
            continue
        frame = buf[i:i + length]
        exp = frame[-2] | (frame[-1] << 8)
        if crc16(frame[:-2]) == exp:
            yield frame
            i += length
        else:
            i += 1


